def dots(text, adv=6):
    """List of (col, row) lit dots for a string; each char advances `adv` columns."""
    out = []
    for i, ch in enumerate(text.upper()):
        g = G.get(ch, G[" "])
        for r, row in enumerate(g):
            for c, v in enumerate(row):
                if v == "#": out.append((i * adv + c, r))
    return out
