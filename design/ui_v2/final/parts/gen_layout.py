"""Export everything the JUCE editor needs: assets (Source/ui_assets/) and Source/UiLayout.h (all geometry in
1600x1000 UI px, assets at 2x). Run after build_ui.py, fit_text.py, fit_display.py, matcap/stitch."""
import json, os, shutil
import numpy as np
from PIL import Image
H = os.path.dirname(os.path.abspath(__file__)); os.chdir(H)
ROOT = os.path.abspath("../../../..")                       # repo root
OUT = os.path.join(ROOT, "Source", "ui_assets"); os.makedirs(OUT, exist_ok=True)
ST = "../strips"; RX, RY = 1600 / 1568, 1000 / 1003          # reference px -> UI px
S = json.load(open("sprites/sprites.json")); T = json.load(open("text.json")); D = json.load(open("display.json"))
strips = json.load(open(os.path.join(ST, "strips.json")))
lines = ["// Generated by design/ui_v2/final/parts/gen_layout.py -- do not edit by hand.",
         "// UI geometry in 1600x1000 px; bitmaps are 2x (3200x2000 canvas).", "#pragma once", "namespace UiLayout {"]
def L(s): lines.append("    " + s)
def rect(name, x0, y0, x1, y1): L("inline constexpr float %s[4] = { %.2ff, %.2ff, %.2ff, %.2ff };   // x, y, w, h" % (name, x0, y0, x1 - x0, y1 - y0))
def refrect(name, x0, y0, x1, y1): rect(name, x0 * RX, y0 * RY, x1 * RX, y1 * RY)

# background (JPEG keeps the plugin small; photo content)
Image.open("bg_clean.png").convert("RGB").save(os.path.join(OUT, "ui_bg.jpg"), quality=97, subsampling=0)
# sprites (canvas boxes -> UI rects)
for k, v in S.items():
    shutil.copy("sprites/%s.png" % k, os.path.join(OUT, "sp_%s.png" % k)); b = v["box"]
    rect("sp_" + k, b[0] / 2, b[1] / 2, b[2] / 2, b[3] / 2)
# meter segments (x ranges inside the meter sprite, in sprite px)
mo = np.asarray(Image.open("sprites/meter_on.png"), np.float32)
Lm = mo[mo.shape[0] // 3:2 * mo.shape[0] // 3, :, :3].mean(2).mean(0); lit = Lm > 0.5 * (np.percentile(Lm, 90) + np.percentile(Lm, 10))
lit[:6] = False; lit[-6:] = False; e = np.flatnonzero(np.diff(lit.astype(int)))
segs = [(e[i] + 1, e[i + 1] + 1) for i in range(0, len(e) - 1, 2)]
L("inline constexpr int meterSegments = %d;" % len(segs))
L("inline constexpr int meterSegEnd[%d] = { %s };   // sprite px (2x) where each lit segment ends" % (len(segs), ", ".join(str(int(b)) for a, b in segs)))
# slider: value 0..1 runs from the first to the last tick under the groove; fill is clipped at the handle centre
cl = np.asarray(Image.open("bg_clean.png"), np.float32); tb = S["slider_thumb"]["box"]
th = np.asarray(Image.open("sprites/slider_thumb.png"), np.float32)[..., 3]
ys, xs = np.where(th > 128); tcx = S["slider_thumb"]["handle_cx"]; tcy = tb[1] + (ys.min() + ys.max()) / 2
band = cl[tb[1]:tb[3], tb[0]:tb[2]].mean(2); rows = band.mean(1)
tick_row = int(np.argmax(np.where(np.arange(len(rows)) > (ys.max() + ys.min()) / 2 + 4, band.max(1) - np.median(band, 1), 0)))
prof = band[tick_row]; on = prof > (prof.max() + np.median(prof)) / 2; e2 = np.flatnonzero(np.diff(on.astype(int)))
ticks = [(e2[i] + e2[i + 1]) / 2 + 1 + tb[0] for i in range(0, len(e2) - 1, 2)]
x0s, x1s = ticks[0], ticks[-1]
L("inline constexpr float sliderX0 = %.2ff, sliderX1 = %.2ff;   // handle centre at value 0 and 1 (UI px) = first/last tick" % (x0s / 2, x1s / 2))
L("inline constexpr float sliderThumbCx = %.2ff;               // handle centre as drawn in sp_slider_thumb" % (tcx / 2))
print("slider ticks:", len(ticks), "from %.0f to %.0f canvas; handle drawn at %.0f" % (x0s, x1s, tcx))
# knob strips
for f_ in os.listdir(OUT):   # drop strips from earlier exports (domes are pointer-only now)
    if f_.startswith("knob_") or f_.startswith("ptr_"): os.remove(os.path.join(OUT, f_))
PS = json.load(open(os.path.join(ST, "ptr_strips.json")))
for K_, p in PS.items():   # cream domes: body is in the background, only the pointer turns
    shutil.copy(os.path.join(ST, "ptr_%s.png" % K_), os.path.join(OUT, "ptr_%s.png" % K_.lower()))
    L("inline constexpr int ptr%sFrames = %d, ptr%sFramePx = %d;" % (K_, p["frames"], K_, p["frame_px"]))
    L("inline constexpr float ptr%sOrigin[2] = { %.2ff, %.2ff };   // UI px, top-left of each frame" % (K_, p["origin_canvas"][0] / 2, p["origin_canvas"][1] / 2))
for st in ("scallop", "space"):
    if st not in strips: continue
    m = strips[st]; shutil.copy(os.path.join(ST, "knob_%s.png" % st), os.path.join(OUT, "knob_%s.png" % st))
    L("inline constexpr int %sFrames = %d, %sFramePx = %d;   // 2x px, frames stacked vertically" % (st, m["frames"], st, m["frame_px"][0]))
    for i, inst in enumerate(m["instances"]):
        L("inline constexpr float %sCentre%d[2] = { %.2ff, %.2ff };" % (st, i, inst["cx"], inst["cy"]))
# text items
fonts = sorted({t["font"] for t in T.values()})
for f in fonts: shutil.copy("../../fonts/%s.ttf" % f, os.path.join(OUT, f.replace("-", "_") + ".ttf"))
for k, t in T.items():
    c = t["colour"]
    L("inline constexpr float txt_%s[4] = { %.2ff, %.2ff, %.2ff, %.2ff };   // ink centre x, ink centre y, ink width of txtRef, ink left" %
      (k, t["ink_cx"] / 2, t["ink_cy"] / 2, t["ink_w"] / 2, t["ink_left"] / 2))
    L("inline constexpr const char* txtRef_%s = \"%s\";" % (k, t["text"]))
    L("inline constexpr unsigned int txtColour_%s = 0xff%02x%02x%02x;   // font %s" % (k, *[int(round(min(255, max(0, v)))) for v in c], t["font"]))
# small-window variant (small_1): live text positions/sizes measured on it (small_labels.py)
if os.path.exists("text_small.json"):
    for k, t in json.load(open("text_small.json")).items():
        c = t["colour"]
        L("inline constexpr float txtS_%s[4] = { %.2ff, %.2ff, %.2ff, %.2ff };   // small window: ink cx, cy, ink width of txtRef, ink left" %
          (k, t["ink_cx"] / 2, t["ink_cy"] / 2, t["ink_w"] / 2, t["ink_left"] / 2))
        L("inline constexpr unsigned int txtSColour_%s = 0xff%02x%02x%02x;" % (k, *[int(round(min(255, max(0, v)))) for v in c]))
# per-preset instruments (skins.py): opaque layers over the walnut plate
if os.path.exists("skins/skins.json"):
    SKN = json.load(open("skins/skins.json"))
    for f_ in os.listdir(OUT):
        if f_.startswith("skin_"): os.remove(os.path.join(OUT, f_))
    for sk, v in SKN.items():
        shutil.copy("skins/skin_%s.jpg" % sk, os.path.join(OUT, "skin_%s.jpg" % sk)); b = v["box"]
        rect("skin_" + sk, b[0] / 2, b[1] / 2, b[2] / 2, b[3] / 2)
# dot-matrix display
K = np.load("display_kernel.npy"); km = float(K.max())
Image.fromarray(np.clip(K / km * 255, 0, 255).astype(np.uint8)).save(os.path.join(OUT, "display_dot.png"))
b = D["box_canvas"]; rect("displayBox", b[0] / 2, b[1] / 2, b[2] / 2, b[3] / 2)
L("inline constexpr float dispPitchX = %.4ff, dispPitchY = %.4ff, dispOriginY = %.3ff, dispCentreX = %.3ff;   // 2x px, relative to displayBox"
  % (D["pitch"], D["pitch_y"], D["origin"][1], D["text_centre_x"]))
L("inline constexpr float dispKernelMax = %.4ff;   // display_dot.png value 255 == this much added per channel" % km)
# the steel: fret -> x (piecewise through the printed fret numbers' centres; fret 0 = start of the grid), strings, bar
FRETS = [(0, 990), (3, 1148), (5, 1309), (7, 1458), (9, 1590.5), (10, S["tone_bar"]["bar_cx"]), (12, 1762), (15, 1904), (17, 1994), (19, 2082), (21, 2133), (24, 2216)]
L("inline constexpr int numFretAnchors = %d;" % len(FRETS))
L("inline constexpr float fretAnchor[%d][2] = { %s };   // (fret, x UI px)" % (len(FRETS), ", ".join("{ %.1ff, %.2ff }" % (f, x / 2) for f, x in FRETS)))
STR = [385, 400.7, 417, 433, 450, 467.7, 484, 502, 519, 535.7]   # canvas rows, string 1 (far side, top) .. string 10
L("inline constexpr float stringY[10] = { %s };   // UI px, string 1 (top) .. 10" % ", ".join("%.2ff" % (y / 2) for y in STR))
L("inline constexpr float stringEndX = %.2ff;    // where the vibrating length ends (changer side), UI px" % (2660 / 2))
L("inline constexpr float barRefCx = %.2ff, barRefFret = 10.0f;   // sp_tone_bar is drawn for the bar at this x" % (S["tone_bar"]["bar_cx"] / 2))
rect("hitFretboard", 984 / 2, 360 / 2, 2340 / 2, 548 / 2); rect("hitPluck", 2340 / 2, 360 / 2, 2660 / 2, 548 / 2)
# hit areas (reference px)
refrect("hitPrev", 532, 41, 582, 81); refrect("hitNext", 985, 41, 1035, 81)
refrect("hitMode", 183, 912, 462, 950); refrect("hitMidiLearn", 1332, 912, 1483, 950)
refrect("hitSlider", 752, 915, 1168, 958)
pb = json.load(open("aligned/pedals_unlit.json"))["part_box_canvas"]; cw = (pb[2] - pb[0]) / 3
for i, k in enumerate("ABC"): rect("hitPedal" + k, (pb[0] + i * cw) / 2, pb[1] / 2, (pb[0] + (i + 1) * cw) / 2, pb[3] / 2)
refrect("hitLKL", 1262, 715, 1352, 860); refrect("hitLKR", 1388, 715, 1478, 860)
lines.append("}"); open(os.path.join(ROOT, "Source", "UiLayout.h"), "w").write("\n".join(lines) + "\n")
print("wrote Source/UiLayout.h and", len(os.listdir(OUT)), "assets;", sum(os.path.getsize(os.path.join(OUT, f)) for f in os.listdir(OUT)) // 1024, "KB")
