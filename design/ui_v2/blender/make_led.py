def render(lines, cols=20, pitch=14, dot=10):
    rows = 7 * len(lines) + 3 * (len(lines) - 1)
    W, H = cols * 6 * pitch + 2 * pitch, rows * pitch + 2 * pitch
    lit = Image.new("RGB", (W, H), (0, 0, 0)); d = ImageDraw.Draw(lit)
    base = Image.new("RGB", (W, H), (10, 6, 3)); db = ImageDraw.Draw(base)
    for li, line in enumerate(lines):
        y0 = pitch + li * 10 * pitch
        for ci in range(cols):
            ch = line[ci] if ci < len(line) else " "
            g = G[ch]
            for r in range(7):
                for c in range(5):
                    x = pitch + (ci * 6 + c) * pitch; y = y0 + r * pitch
                    box = (x, y, x + dot, y + dot)
                    db.ellipse(box, fill=(34, 17, 6))
                    if g[r][c] == "#":
                        d.ellipse(box, fill=(255, 150, 30))
    glow = lit.filter(ImageFilter.GaussianBlur(pitch * 0.6))
    out = Image.composite(lit, base, lit.convert("L").point(lambda v: 255 if v > 10 else 0))
    from PIL import ImageChops
    return ImageChops.add(out, glow.point(lambda v: int(v * 0.55)))

